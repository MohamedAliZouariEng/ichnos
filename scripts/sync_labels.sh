#!/usr/bin/env bash
# Create or update the Ichnos label set on a GitHub repository.
# Usage: scripts/sync_labels.sh [owner/repo]   (defaults to the current repo)
set -euo pipefail
REPO="${1:-$(gh repo view --json nameWithOwner -q .nameWithOwner)}"
echo "Syncing Ichnos labels to $REPO"

while IFS='|' read -r name color description; do
  [[ -z "$name" || "$name" == \#* ]] && continue
  gh label create "$name" --repo "$REPO" --color "$color" \
    --description "$description" --force
done <<'LABELS'
