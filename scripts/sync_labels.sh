type:epic|8250df|Coherent deliverable connected to an Initiative
type:story|0969da|Implementable unit of work with acceptance criteria
type:bug|d73a4a|Defect in existing behaviour
status:draft|ededed|Not yet reviewed
status:needs-review|fbca04|Waiting for human review
status:approved|0e8a16|Approved by a human
status:ready-for-implementation|1d76db|Approved and ready to be picked up
status:in-progress|c5def5|Work has started
status:blocked|b60205|Blocked by a dependency or open question
status:done|6e7781|Completed
agent:generated|bfd4f2|Content generated by the Ichnos agent workflow
priority:p0|b60205|Critical: do now
priority:p1|d93f0b|High
priority:p2|fbca04|Medium
priority:p3|c2e0c6|Low
LABELS
